    (project/'project.pbxproj').write_text('// !$*UTF8*$!\n{archiveVersion = 1; classes = {}; objectVersion = 56; objects = {\n'+'\n'.join(objects)+f'\n}}; rootObject = {ident(1)};}}\n')
    scheme = project/'xcshareddata/xcschemes/SimulatorProof.xcscheme'
    scheme.parent.mkdir(parents=True, exist_ok=True)
    app = f'<BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="{ident(2)}" BuildableName="FloatingVoice.app" BlueprintName="FloatingVoice" ReferencedContainer="container:FloatingVoice.xcodeproj"/>'
    test = f'<BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="{ident(300)}" BuildableName="VoiceLoopUITests.xctest" BlueprintName="VoiceLoopUITests" ReferencedContainer="container:FloatingVoice.xcodeproj"/>'
