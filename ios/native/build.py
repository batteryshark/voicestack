def generate():
    canvas_preflight()
    presentation = json.loads((ROOT/'shared/presentation.json').read_text())['assistantLabel']
    (ROOT/'app/Sources/FloatingVoiceCore/AgentPresentation.swift').write_text(
        '// Generated by native/build.py from shared/presentation.json. Do not edit the label here.\n'
        'public enum AgentPresentation {\n'
        f'    public static let name = {json.dumps(presentation)}\n'
        '    public static func roleLabel(_ role: String) -> String { role == "Chief" ? name : role }\n'
        '}\n')
    project = ROOT / 'native/FloatingVoice.xcodeproj'
    project.mkdir(exist_ok=True)
    sources = sorted((ROOT / 'app/Sources/FloatingVoiceCore').glob('*.swift')) + [p for p in sorted((ROOT / 'native').glob('*.swift')) if p.name != 'remux_proof.swift']
    def ident(n): return f'{n:024X}'
    objects = []
    refs, builds = [], []
    for i, path in enumerate(sources):
        ref, build = ident(100+i*2), ident(101+i*2)
        refs.append(ref); builds.append(build)
        relative = os.path.relpath(path, ROOT/'native')
        objects += [f'{ref} = {{isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = "{relative}"; sourceTree = "<group>";}};', f'{build} = {{isa = PBXBuildFile; fileRef = {ref};}};']
    def obj(n, body): objects.append(f'{ident(n)} = {{{body}}};')
    obj(1, f'isa = PBXProject; attributes = {{TargetAttributes = {{{ident(2)} = {{SystemCapabilities = {{com.apple.Push = {{enabled = 1;}};}};}};}};}}; buildConfigurationList = {ident(10)}; compatibilityVersion = "Xcode 14.0"; developmentRegion = en; knownRegions = (en, Base); mainGroup = {ident(3)}; productRefGroup = {ident(4)}; projectDirPath = ""; projectRoot = ""; targets = ({ident(2)},{ident(300)});')
    obj(2, f'isa = PBXNativeTarget; buildConfigurationList = {ident(11)}; buildPhases = ({ident(5)}, {ident(6)}, {ident(7)}); buildRules = (); dependencies = (); name = FloatingVoice; productName = FloatingVoice; productReference = {ident(8)}; productType = "com.apple.product-type.application";')
    obj(20, 'isa = PBXFileReference; lastKnownFileType = folder.icon; path = Icon/AppIcon.icon; sourceTree = "<group>";')
    obj(21, f'isa = PBXBuildFile; fileRef = {ident(20)};')
    music = (ROOT / 'native/HoldMusic.pcm').is_file()
    if music:
        obj(22, 'isa = PBXFileReference; lastKnownFileType = file; path = HoldMusic.pcm; sourceTree = "<group>";')
        obj(23, f'isa = PBXBuildFile; fileRef = {ident(22)};')
    obj(3, f'isa = PBXGroup; children = ({",".join(refs)},{ident(20)},{ident(301)},{ident(4)}); sourceTree = "<group>";')
    obj(4, f'isa = PBXGroup; children = ({ident(8)},{ident(303)}); name = Products; sourceTree = "<group>";')
    obj(5, f'isa = PBXSourcesBuildPhase; buildActionMask = 2147483647; files = ({",".join(builds)}); runOnlyForDeploymentPostprocessing = 0;')
    for n, isa in [(6, 'PBXFrameworksBuildPhase'), (7, 'PBXResourcesBuildPhase')]: obj(n, f'isa = {isa}; buildActionMask = 2147483647; files = ({(ident(21) + ("," + ident(23) if music else "")) if n == 7 else ""}); runOnlyForDeploymentPostprocessing = 0;')
    obj(8, 'isa = PBXFileReference; explicitFileType = wrapper.application; includeInIndex = 0; path = FloatingVoice.app; sourceTree = BUILT_PRODUCTS_DIR;')
    for n, first in [(10,12),(11,14)]: obj(n, f'isa = XCConfigurationList; buildConfigurations = ({ident(first)}, {ident(first+1)}); defaultConfigurationIsVisible = 0; defaultConfigurationName = Release;')
    for n, name in [(12,'Debug'),(13,'Release')]:
        debug = 'SWIFT_ACTIVE_COMPILATION_CONDITIONS = DEBUG;' if name == 'Debug' else ''
        obj(n, f'isa = XCBuildConfiguration; buildSettings = {{SDKROOT = iphoneos; IPHONEOS_DEPLOYMENT_TARGET = 17.0; SWIFT_VERSION = 5.0; CLANG_ENABLE_MODULES = YES; {debug}}}; name = {name};')
    for n, name in [(14,'Debug'),(15,'Release')]: obj(n, f'isa = XCBuildConfiguration; buildSettings = {{PRODUCT_NAME = "$(TARGET_NAME)"; PRODUCT_BUNDLE_IDENTIFIER = {BUNDLE}; DEVELOPMENT_TEAM = "{TEAM}"; CODE_SIGN_STYLE = Automatic; CODE_SIGN_ENTITLEMENTS = FloatingVoice.entitlements; ASSETCATALOG_COMPILER_APPICON_NAME = AppIcon; INFOPLIST_FILE = ../private/NativeInfo.plist; TARGETED_DEVICE_FAMILY = 1; SWIFT_OPTIMIZATION_LEVEL = "-O"; ENABLE_BITCODE = NO;}}; name = {name};')
    # Dedicated UI test scheme; ordinary device archive still builds only FloatingVoice.
    obj(300, f'isa = PBXNativeTarget; buildConfigurationList = {ident(307)}; buildPhases = ({ident(304)},{ident(305)}); buildRules = (); dependencies = ({ident(310)}); name = VoiceLoopUITests; productName = VoiceLoopUITests; productReference = {ident(303)}; productType = "com.apple.product-type.bundle.ui-testing";')
    obj(301, 'isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = UITests/VoiceLoopUITests.swift; sourceTree = "<group>";')
    obj(302, f'isa = PBXBuildFile; fileRef = {ident(301)};')
    obj(303, 'isa = PBXFileReference; explicitFileType = wrapper.cfbundle; path = VoiceLoopUITests.xctest; sourceTree = BUILT_PRODUCTS_DIR;')
    # Same presentation factory in app + offline XCTest target; no provider/call is created by its unit test.
    icon_ref = refs[sources.index(ROOT / 'native/CallKitPresentation.swift')]
    obj(311, f'isa = PBXBuildFile; fileRef = {icon_ref};')
    obj(304, f'isa = PBXSourcesBuildPhase; buildActionMask = 2147483647; files = ({ident(302)},{ident(311)}); runOnlyForDeploymentPostprocessing = 0;')
    obj(305, 'isa = PBXFrameworksBuildPhase; buildActionMask = 2147483647; files = (); runOnlyForDeploymentPostprocessing = 0;')
    obj(307, f'isa = XCConfigurationList; buildConfigurations = ({ident(308)}); defaultConfigurationIsVisible = 0; defaultConfigurationName = Debug;')
    obj(308, f'isa = XCBuildConfiguration; buildSettings = {{PRODUCT_NAME = "$(TARGET_NAME)"; PRODUCT_BUNDLE_IDENTIFIER = {BUNDLE}.uitests; GENERATE_INFOPLIST_FILE = YES; TEST_TARGET_NAME = FloatingVoice; IPHONEOS_DEPLOYMENT_TARGET = 17.0; SWIFT_VERSION = 5.0; TARGETED_DEVICE_FAMILY = 1; DEVELOPMENT_TEAM = "{TEAM}"; CODE_SIGN_STYLE = Automatic; "CODE_SIGNING_ALLOWED[sdk=iphonesimulator*]" = NO;}}; name = Debug;')
